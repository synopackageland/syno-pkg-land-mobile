// Embeds src/core/webview/mobile-fit/dsm-fit.{js,css} into fit.gen.ts.
// Run after editing either file: node scripts/gen-mobile-fit.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const dir = 'src/core/webview/mobile-fit/';
export function generate() {
  const js = readFileSync(dir + 'dsm-fit.js', 'utf8');
  const css = readFileSync(dir + 'dsm-fit.css', 'utf8');
  if (js.split('__SPL_FIT_CSS__').length !== 2) throw new Error('dsm-fit.js must contain the CSS placeholder exactly once');
  const source = js.replace('__SPL_FIT_CSS__', () => JSON.stringify(css));
  return `// Generated by scripts/gen-mobile-fit.mjs from dsm-fit.js and dsm-fit.css. Do not edit.\nexport const fitSource = ${JSON.stringify(source)};\n`;
}
if (import.meta.url === `file://${process.argv[1]}`) writeFileSync(dir + 'fit.gen.ts', generate());
